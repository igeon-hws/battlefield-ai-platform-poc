"""Generate frontend-only types from Python's authoritative Pydantic contracts."""

import json
from pathlib import Path

from battlefield_ontology import (
    Equipment,
    Observation,
    SnapshotRef,
    SourceRef,
    SourceSnapshotSet,
    SourceSnapshotSetV5,
    System,
    Unit,
)
from c4i_contracts import Entity, EntityFilter, EntityPatch
from platform_api.demo import SessionInput
from platform_api.multi_app import ComparisonInput, Question
from platform_contracts.models import AnalysisResult, ProvenancedAnalysisResult
from pydantic import BaseModel
from semantic_api.objects import ObjectRequest

root = Path(__file__).resolve().parents[1]
models: list[type[BaseModel]] = [
    Entity,
    EntityFilter,
    EntityPatch,
    AnalysisResult,
    ProvenancedAnalysisResult,
    Equipment,
    Unit,
    System,
    Observation,
    SourceRef,
    SnapshotRef,
    SourceSnapshotSet,
    SourceSnapshotSetV5,
    SessionInput,
    ObjectRequest,
    Question,
    ComparisonInput,
]
schemas = {model.__name__: model.model_json_schema(by_alias=True) for model in models}
definitions = {}
for schema in schemas.values():
    definitions.update(schema.get("$defs", {}))
definitions.update(schemas)


def ts(schema):
    if "const" in schema:
        return json.dumps(schema["const"])
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if not schema.get("properties") and isinstance(schema.get("additionalProperties"), dict):
            return f"Record<string, {ts(schema['additionalProperties'])}>"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{key}{'' if key in required else '?'}: {ts(value)}"
                for key, value in schema.get("properties", {}).items()
            )
            + " }"
        )
    if kind == "array":
        return f"({ts(schema['items'])})[]"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


target = root / "frontend/generated/contracts.ts"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(
    "// Generated by scripts/export_contracts.py; edit Python models instead.\n"
    + "\n".join(f"export type {name} = {ts(schema)};" for name, schema in definitions.items())
    + "\n",
    encoding="utf-8",
)
(root / "schemas").mkdir(exist_ok=True)
(root / "schemas/contracts.json").write_text(
    json.dumps(schemas, ensure_ascii=False, indent=2), encoding="utf-8"
)
print("Exported Pydantic schemas and UI types")
